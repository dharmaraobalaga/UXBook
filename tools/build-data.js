#!/usr/bin/env node
/* --------------------------------------------------------------------------
   Build data/parts.js from the raw source files in data/raw/.

   Usage:   node tools/build-data.js
   Input:   data/raw/part-01.txt … data/raw/part-57.txt (any "part-*.txt")
            Each file = one part, pasted exactly as it appears in ChatGPT.
   Output:  data/parts.js  (window.BOOK_PARTS = [...])
            data/content-audit.json (counts + warnings)

   Existing question IDs ("q-447") are derived from the question number, so
   bookmarks, notes and progress keep working when you add new parts.
   -------------------------------------------------------------------------- */
'use strict';
const fs = require('fs');
const path = require('path');
const { parsePart } = require('../js/parser.js');

const root = path.join(__dirname, '..');
const rawDir = path.join(root, 'data', 'raw');
const files = fs.readdirSync(rawDir).filter(f => /^part-.*\.txt$/i.test(f)).sort();

const parts = [];
const audit = { generatedAt: new Date().toISOString(), parts: [], warnings: [] };

for (const f of files) {
  const text = fs.readFileSync(path.join(rawDir, f), 'utf8');
  const hint = (f.match(/part-(\d+)/i) || [])[1];
  const { part, warnings } = parsePart(text, { partNumber: hint });
  parts.push(part);
  audit.parts.push({
    file: f, partNumber: part.partNumber, title: part.title,
    questions: part.questions.length, range: part.questionStart ? `Q${part.questionStart}–Q${part.questionEnd}` : '—',
    revisionRows: part.revision.length, vocabulary: part.vocabulary.length,
    speakingSentences: part.speakingPractice ? part.speakingPractice.sentences.length : 0
  });
  warnings.forEach(w => audit.warnings.push(`Part ${part.partNumber} (${f}): ${w}`));
}

parts.sort((a, b) => a.partNumber - b.partNumber);
const present = new Set(parts.map(p => p.partNumber));
const maxPart = Math.max(57, ...present);
audit.missingParts = [];
for (let n = 1; n <= maxPart; n++) if (!present.has(n)) audit.missingParts.push(n);
audit.totalQuestions = parts.reduce((s, p) => s + p.questions.length, 0);

const banner = `/* AUTO-GENERATED by tools/build-data.js on ${audit.generatedAt}.
   Edit the files in data/raw/ and re-run the script instead of editing this file.
   Parts: ${parts.length} · Questions: ${audit.totalQuestions} */\n`;
fs.writeFileSync(path.join(root, 'data', 'parts.js'), banner + 'window.BOOK_PARTS = ' + JSON.stringify(parts, null, 1) + ';\n');
fs.writeFileSync(path.join(root, 'data', 'content-audit.json'), JSON.stringify(audit, null, 2));

console.log(`Built ${parts.length} part(s), ${audit.totalQuestions} question(s).`);
console.log(`Missing parts (1–${maxPart}): ${audit.missingParts.length ? audit.missingParts.join(', ') : 'none'}`);
if (audit.warnings.length) { console.log('Warnings:'); audit.warnings.forEach(w => console.log('  - ' + w)); }
